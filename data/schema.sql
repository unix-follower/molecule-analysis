    FOR column_record IN
        SELECT a.attname, a.attnum
        FROM pg_attribute AS a
        WHERE a.attrelid = 'bace'::regclass
          AND a.attnum > 0
          AND NOT a.attisdropped
          AND col_description(a.attrelid, a.attnum) IS NULL
        ORDER BY a.attnum
    LOOP
        IF column_record.attname LIKE '%\_Key' ESCAPE '\\' THEN
            descriptor_family := left(column_record.attname, length(column_record.attname) - 4);
            EXECUTE format(
                'COMMENT ON COLUMN bace.%I IS %L',
                column_record.attname,
                format('Descriptor family %s: key or presence flag from the original BACE feature export.', descriptor_family)
            );
        ELSIF column_record.attname LIKE '%\_Cnt' ESCAPE '\\' THEN
            descriptor_family := left(column_record.attname, length(column_record.attname) - 4);
            EXECUTE format(
                'COMMENT ON COLUMN bace.%I IS %L',
                column_record.attname,
                format('Descriptor family %s: count value from the original BACE feature export.', descriptor_family)
            );
        ELSIF column_record.attname LIKE '%\_Sum' ESCAPE '\\' THEN
            descriptor_family := left(column_record.attname, length(column_record.attname) - 4);
            EXECUTE format(
                'COMMENT ON COLUMN bace.%I IS %L',
                column_record.attname,
                format('Descriptor family %s: summed value from the original BACE feature export.', descriptor_family)
            );
        ELSIF column_record.attname LIKE '%\_Avg' ESCAPE '\\' THEN
            descriptor_family := left(column_record.attname, length(column_record.attname) - 4);
            EXECUTE format(
                'COMMENT ON COLUMN bace.%I IS %L',
                column_record.attname,
                format('Descriptor family %s: average value from the original BACE feature export.', descriptor_family)
            );
        ELSE
            EXECUTE format(
                'COMMENT ON COLUMN bace.%I IS %L',
                column_record.attname,
                format('Descriptor column from the original BACE CSV: %s.', column_record.attname)
            );
        END IF;
