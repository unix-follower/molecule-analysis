CREATE INDEX IF NOT EXISTS idx_toxcast_data_smiles
    ON toxcast_data ("smiles");

COMMENT ON TABLE toxcast_data IS 'MoleculeNet ToxCast dataset for multitask toxicity classification across a large assay panel.';
COMMENT ON COLUMN toxcast_data."row_id" IS 'Synthetic surrogate primary key because toxcast_data.csv does not expose a unique natural identifier and smiles values repeat in the current export.';
COMMENT ON COLUMN toxcast_data."smiles" IS 'SMILES representation of the compound; indexed for lookup but not used as the primary key because it is not unique in the current export.';

DO $$
DECLARE
    column_record record;
BEGIN
    FOR column_record IN
        SELECT a.attname, a.attnum
        FROM pg_attribute AS a
        WHERE a.attrelid = 'toxcast_data'::regclass
          AND a.attnum > 0
          AND NOT a.attisdropped
          AND col_description(a.attrelid, a.attnum) IS NULL
        ORDER BY a.attnum
    LOOP
        EXECUTE format(
            'COMMENT ON COLUMN toxcast_data.%I IS %L',
            column_record.attname,
            format('Binary ToxCast assay label from the source dataset for assay %s; null indicates a missing label.', column_record.attname)
        );
    END LOOP;
END $$;
